"""Exploratory diagnostic (not pre-registered): answer bias on the distractor test set.

For each condition, reports the share of "Yes" predictions and the accuracy split by gold label, on the
clean and distractor test sets, as mean +- SD over seeds. Output: results/analysis/distractor_bias.{md,json}.
"""

import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"
OUT = ROOT / "results" / "analysis"

CONDITIONS = [
    "untuned", "shared/clean", "shared/neftune",
    "fold_a/mixed3_f0.50", "fold_b/mixed3_f0.50", "fold_b/single_distractor",
]
SETS = ["clean", "distractor"]


def load_labels() -> list[int]:
    with open(ROOT / "data" / "splits" / "test.jsonl", encoding="utf-8") as f:
        return [json.loads(line)["label"] for line in f if line.strip()]


def stats(p_yes: list[float], labels: list[int]) -> dict:
    pred = [p > 0.5 for p in p_yes]
    n_yes = sum(labels)
    n_no = len(labels) - n_yes
    return {
        "pred_yes_rate": sum(pred) / len(pred),
        "acc_gold_yes": sum(1 for p, y in zip(pred, labels) if y == 1 and p) / n_yes,
        "acc_gold_no": sum(1 for p, y in zip(pred, labels) if y == 0 and not p) / n_no,
        "acc": sum(1 for p, y in zip(pred, labels) if p == bool(y)) / len(labels),
    }


def main() -> None:
    labels = load_labels()
    per = defaultdict(lambda: defaultdict(list))
    for run_dir in sorted(RUNS.iterdir()):
        cfg_path = run_dir / "run_config.json"
        if not cfg_path.exists():
            continue
        cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
        if cfg.get("tag") or cfg.get("eval_limit") or cfg.get("max_steps_override"):
            continue
        if cfg["condition"] not in CONDITIONS:
            continue
        preds = json.loads((run_dir / "predictions.json").read_text(encoding="utf-8"))
        for s in SETS:
            per[cfg["condition"]][s].append(stats(preds[s], labels))

    summary = {"gold_yes_rate": sum(labels) / len(labels), "conditions": {}}
    lines = [
        "# Distractor answer-bias diagnostic (exploratory, auto-generated by scripts/diag_distractor.py)",
        "",
        f"Gold 'Yes' rate on the test set: {summary['gold_yes_rate']:.3f}. Values: mean +- SD over seeds.",
        "",
        "| condition | n | test set | predicted Yes | acc on gold Yes | acc on gold No | acc |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in CONDITIONS:
        summary["conditions"][c] = {}
        for s in SETS:
            rows = per[c][s]
            agg = {}
            for k in rows[0]:
                vals = [r[k] for r in rows]
                agg[k] = (statistics.mean(vals), statistics.stdev(vals) if len(vals) > 1 else 0.0)
            summary["conditions"][c][s] = {"n": len(rows), **agg}
            cell = lambda k: f"{100 * agg[k][0]:.1f} +- {100 * agg[k][1]:.1f}"
            lines.append(f"| {c} | {len(rows)} | {s} | {cell('pred_yes_rate')} | {cell('acc_gold_yes')} | "
                         f"{cell('acc_gold_no')} | {cell('acc')} |")

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "distractor_bias.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (OUT / "distractor_bias.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
